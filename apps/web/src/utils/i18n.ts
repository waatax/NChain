export function useI18n() {
  const appStore = useAppStore();
  const lang = computed(() => appStore.settings.lang || 'zh-TW');

  const t = (text: string) => {
    if (!text) return '';
    if (lang.value === 'zh-TW') return text;
    
    // Dynamic text replacement for string interpolation (like "第 {n} 題")
    // If the template has {n} or other placeholders, we search for a matching translation key
    let key = text.trim();
    
    // Check direct translation
    if (translations[key]) {
      return translations[key];
    }
    
    // Fallback dictionary-based translation helper for simple matches or text fragments
    return translations[key] || text;
  };

  return { t, lang };
}
